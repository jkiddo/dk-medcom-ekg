"""Generate deterministic synthetic ECG examples and their matching PDF.

Requires Python 3 and reportlab. Run from any directory. The signals are
illustrative test data, not recordings from a patient or diagnostic fixtures.
"""
import base64
import math
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas

ROOT = Path(__file__).resolve().parents[1]
LEADS = [
    ("I", 131329), ("II", 131330), ("III", 131389),
    ("aVR", 131390), ("aVL", 131391), ("aVF", 131392),
    ("V1", 131331), ("V2", 131332), ("V3", 131333),
    ("V4", 131334), ("V5", 131335), ("V6", 131336),
]
OBS12 = "66d6516f-382d-442f-993f-9eb96f0700f6"
OBS3 = "db5dd8eb-0432-4745-9522-a48932122faf"
COMPOSITION = "f1be996e-854b-486b-bb3a-63268dcd9a73"
BUNDLE = "83f3b8a2-a94d-4221-aacf-13e72e534cf2"
PATIENT = "379ebb53-11e3-42ac-b9db-0bad0ece46d1"
ORGANIZATION = "f8d0eb07-5336-4005-9081-b065f9a82663"
BASE = "http://medcomfhir.dk/ig/ekgrecording"
START = "2026-01-14T10:00:00+01:00"
END = "2026-01-14T10:00:01+01:00"


def signals():
    """500 samples per lead, period 2 ms, integer values in 0.001 mV steps."""
    def wave(t, r=1.0, s=-0.2, p=0.1, tw=0.25):
        def g(center, width):
            return math.exp(-0.5 * ((t - center) / width) ** 2)
        return p*g(0.18, 0.025) - 0.08*g(0.35, 0.008) + r*g(0.38, 0.010) + s*g(0.41, 0.012) + tw*g(0.65, 0.055)

    times = [i / 500 for i in range(500)]
    # Even limb values keep all derived limb leads exact at integer precision.
    lead_i = [2 * round(500 * wave(t, r=0.8, s=-0.15)) for t in times]
    lead_ii = [2 * round(500 * wave(t, r=1.1, s=-0.25, p=0.15, tw=0.3)) for t in times]
    result = [lead_i, lead_ii,
              [b-a for a, b in zip(lead_i, lead_ii)],
              [-(a+b)//2 for a, b in zip(lead_i, lead_ii)],
              [a-b//2 for a, b in zip(lead_i, lead_ii)],
              [b-a//2 for a, b in zip(lead_i, lead_ii)]]
    for r, s, tw in [(0.2, -0.8, -0.1), (0.4, -0.6, 0.1), (0.7, -0.4, 0.2),
                     (1.2, -0.25, 0.3), (1.0, -0.15, 0.25), (0.8, -0.1, 0.2)]:
        result.append([round(1000 * wave(t, r=r, s=s, tw=tw)) for t in times])
    return result


def make_pdf(data):
    path = ROOT / "input/images/ekg-synthetic-waveforms.pdf"
    pdf = canvas.Canvas(str(path), pagesize=A4, invariant=1, pageCompression=1)
    pdf.setTitle("Synthetic twelve-lead ECG - numerical example")
    pdf.setAuthor("MedCom ECG implementation guide example")
    pdf.setFont("Helvetica-Bold", 17)
    pdf.drawString(18*mm, 278*mm, "Synthetic twelve-lead ECG")
    pdf.setFont("Helvetica", 10)
    for y, line in [(269, "Illustrative test data only - not for clinical interpretation."),
                    (260, "Test patient: Else Test Lauridsen | Test CPR: 020191-9990"),
                    (253, "2026-01-14 10:00:00 to 10:00:01 +01:00"),
                    (246, "500 samples/lead | 500 Hz | 25 mm/s | 10 mm/mV")]:
        pdf.drawString(18*mm, y*mm, line)
    # Two columns of six simultaneous one-second strips, at physical ECG scale.
    for n, ((name, _), values) in enumerate(zip(LEADS, data)):
        x = (30 + (n // 6) * 90) * mm
        baseline = (222 - (n % 6) * 31) * mm
        pdf.setStrokeColor(colors.HexColor("#f3d8db"))
        pdf.setLineWidth(0.25)
        for gx in range(26):
            pdf.line(x+gx*mm, baseline-12*mm, x+gx*mm, baseline+12*mm)
        for gy in range(-12, 13):
            pdf.line(x, baseline+gy*mm, x+25*mm, baseline+gy*mm)
        pdf.setFillColor(colors.black)
        pdf.setFont("Helvetica-Bold", 10)
        pdf.drawString(x-12*mm, baseline, name)
        pdf.setStrokeColor(colors.HexColor("#162a43"))
        pdf.setLineWidth(0.7)
        pathline = pdf.beginPath()
        for i, value in enumerate(values):
            px, py = x + (i*0.002)*25*mm, baseline + value*0.001*10*mm
            (pathline.moveTo if i == 0 else pathline.lineTo)(px, py)
        pdf.drawPath(pathline)
        pdf.setFont("Helvetica", 8)
        pdf.drawString(x, baseline-16*mm, "0 s")
        pdf.drawRightString(x+25*mm, baseline-16*mm, "1 s")
    pdf.setFont("Helvetica", 9)
    pdf.drawString(18*mm, 30*mm, "Every trace is plotted from the exact samples in the FHIR example.")
    pdf.drawString(18*mm, 24*mm, "All leads share the start time. Last sample: +0.998 s; interval end: +1.000 s.")
    pdf.save()
    return base64.b64encode(path.read_bytes()).decode("ascii")


def generate():
    data = signals()
    attachment = make_pdf(data)
    lines = [
        "// Generated by scripts/generate-numerical-examples.py; do not edit by hand.",
        "// All sample values are explicit; no omitted values or placeholders.",
        "RuleSet: SyntheticEkgRecording",
        '* status = #final',
        '* code.coding[LOINC] = http://loinc.org#11524-6 "EKG study"',
        f'* subject = Reference({PATIENT})',
        f'* performer = Reference({ORGANIZATION})',
        f'* effectivePeriod.start = "{START}"', f'* effectivePeriod.end = "{END}"',
        '* extension[valueAttachment].url = $MedComObsExtValueAttachment',
        '* extension[valueAttachment].valueAttachment.contentType = #application/pdf',
        '* extension[valueAttachment].valueAttachment.title = "Elektrokardiogram-12-aflednings"',
        f'* extension[valueAttachment].valueAttachment.data = "{attachment}"', "",
    ]
    for instance_id, count, title in [(OBS12, 12, "PDF and all twelve numerical ECG leads"),
                                      (OBS3, 3, "PDF and numerical leads I, II and III")]:
        lines.extend([
            f'Instance: {instance_id}', 'InstanceOf: MedComEkgRecordingObservation',
            'Usage: #example', f'Title: "{title}"',
            f'Description: "Synthetic one-second recording with {count} explicit arrays of 500 samples. The PDF shows all twelve leads; only the supplied components are available numerically."',
            '* insert SyntheticEkgRecording',
            '* identifier.system = "urn:ietf:rfc:3986"',
            f'* identifier.value = "urn:uuid:{instance_id}"',
            f'* note.text = "Synthetic example, not a patient recording. PDF contains twelve leads; {count} leads supplied as numerical samples."',
            '* text.status = #additional',
            f'* text.div = """<div xmlns=\"http://www.w3.org/1999/xhtml\"><p>Synthetic ECG test data, not for clinical interpretation. {count} numerical leads, 500 samples per lead, 2 ms interval, 0.001 mV per stored unit. Recording: 2026-01-14 10:00:00 to 10:00:01 +01:00. The attached PDF displays the same signals.</p></div>"""',
        ])
        for i, ((name, code), values) in enumerate(zip(LEADS[:count], data[:count])):
            prefix = f"* component[{i}]"
            lines.extend([
                f'{prefix}.code = urn:iso:std:iso:11073:10101#{code} "MDC_ECG_ELEC_POTL_{name.upper()}"',
                f'{prefix}.valueSampledData.origin = 0 \'mV\' "mV"',
                f'{prefix}.valueSampledData.period = 2',
                f'{prefix}.valueSampledData.factor = 0.001',
                f'{prefix}.valueSampledData.dimensions = 1',
                f'{prefix}.valueSampledData.data = "{" ".join(map(str, values))}"',
            ])
        lines.append("")
    lines.extend([
        f'Instance: {COMPOSITION}', 'InstanceOf: MedComEkgRecordingComposition',
        'Usage: #example', 'Title: "Composition for PDF and twelve numerical ECG leads"',
        '* identifier.system = "urn:ietf:rfc:3986"',
        f'* identifier.value = "urn:uuid:{COMPOSITION}"',
        f'* subject = Reference({PATIENT})', f'* author[institution] = Reference({ORGANIZATION})',
        f'* date = "{END}"', f'* event.period.start = "{START}"', f'* event.period.end = "{END}"',
        f'* section[0].entry[0] = Reference({OBS12})',
        '* meta.profile = "http://medcomfhir.dk/ig/ekg/StructureDefinition/medcom-ekg-recording-composition|2.0"',
        '', f'Instance: {BUNDLE}', 'InstanceOf: MedComEkgRecordingBundle',
        'Usage: #example', 'Title: "Document Bundle with PDF and all twelve numerical ECG leads"',
        '* type = #document', f'* timestamp = "{END}"',
        '* identifier.system = "urn:ietf:rfc:3986"',
        f'* identifier.value = "urn:uuid:{BUNDLE}"',
    ])
    for resource_type, resource_id in [("Composition", COMPOSITION), ("Observation", OBS12),
                                       ("Patient", PATIENT), ("Organization", ORGANIZATION)]:
        lines.extend([f'* entry[+].fullUrl = "{BASE}/{resource_type}/{resource_id}"',
                      f'* entry[=].resource = {resource_id}'])
    (ROOT / "input/fsh/ExamplesNumerical.fsh").write_text("\n".join(lines) + "\n")
    print("Generated twelve-lead and three-lead Observations, a document Bundle, and a matching PDF.")
    print("Each lead has 500 explicit samples at 500 Hz (2 ms), covering one second.")


if __name__ == "__main__":
    generate()
